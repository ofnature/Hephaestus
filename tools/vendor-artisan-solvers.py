#!/usr/bin/env python3
"""
Vendors Artisan's crafting solvers into the TEST project, so the benchmark can play Artisan's own
decision logic against Hephaestus on the same simulated craft.

    python tools/vendor-artisan-solvers.py            # fetch the pinned commit and regenerate
    python tools/vendor-artisan-solvers.py <commit>   # try a newer Artisan; review the diff

Source: https://github.com/PunishXIV/Artisan (BSD 3-Clause, Copyright (c) 2023, Puni.sh).
The files are copied as they are, then edited ONLY where they touch the game, the UI or Artisan's
plugin instance - each edit below is asserted, so an upstream change that moves the text fails
loudly here instead of silently changing what the benchmark measures. The solvers' logic is never
touched. Everything the removed code needed is provided by the hand-written ArtisanShim.cs.

Nothing here ships in the plugin: the output lives under Hephaestus.Tests/External/Artisan/.
"""
import io
import os
import re
import sys
import urllib.request

PINNED = "c8ee6e0b70e7ca08dcae73d6546095e3baeed9c5"  # Artisan main, 2026-11-11
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Hephaestus.Tests", "External", "Artisan")

HEADER = """// <auto-generated>
// Vendored from PunishXIV/Artisan @ {commit}
//   {path}
// BSD 3-Clause License, Copyright (c) 2023, Puni.sh - see NOTICE.md beside this file.
// Regenerate with tools/vendor-artisan-solvers.py; do not edit by hand. Edits made by that script:
{edits}
// </auto-generated>
#nullable disable
#pragma warning disable

"""


def fetch(commit, path):
    url = f"https://raw.githubusercontent.com/PunishXIV/Artisan/{commit}/{path}"
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8-sig").replace("\r\n", "\n")


class Source:
    def __init__(self, commit, path):
        self.path = path
        self.text = fetch(commit, path)
        self.edits = []

    def drop_usings(self, *names):
        for name in names:
            line = f"using {name};\n"
            assert self.text.count(line) == 1, (self.path, "using", name, self.text.count(line))
            self.text = self.text.replace(line, "")
        self.edits.append("removed usings: " + ", ".join(names))
        return self

    def replace(self, old, new, why):
        assert self.text.count(old) == 1, (self.path, why, self.text.count(old))
        self.text = self.text.replace(old, new)
        self.edits.append(why)
        return self

    def cut(self, start, end, why, keep_end=True):
        """Remove from the line containing `start` up to (not including) the line containing `end`."""
        a = self.text.index(start)
        a = self.text.rfind("\n", 0, a) + 1
        b = self.text.index(end, a + len(start))
        if end.startswith("\n"):
            b += 1  # the marker names the line AFTER the cut by its leading line break
        else:
            b = self.text.rfind("\n", 0, b) + 1 if keep_end else self.text.index("\n", b) + 1
        assert a < b, (self.path, why)
        self.text = self.text[:a] + self.text[b:]
        self.edits.append(why)
        return self

    def cut_regex(self, pattern, why, expected):
        self.text, count = re.subn(pattern, "", self.text, flags=re.S | re.M)
        assert count == expected, (self.path, why, count, expected)
        self.edits.append(f"{why} ({count}x)")
        return self

    def write(self, commit):
        name = os.path.basename(self.path)
        edits = "\n".join(f"//   - {e}" for e in self.edits) or "//   (none)"
        with io.open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as out:
            out.write(HEADER.format(commit=commit, path=self.path, edits=edits))
            out.write(self.text)
        print(f"  {name}: {len(self.edits)} edit(s)")


def main():
    commit = sys.argv[1] if len(sys.argv) > 1 else PINNED
    os.makedirs(OUT, exist_ok=True)
    print(f"Vendoring Artisan @ {commit} into {OUT}")
    A = "Artisan/CraftingLogic/"

    # ---- data types -------------------------------------------------------------------------------
    Source(commit, A + "CraftData/Condition.cs") \
        .drop_usings("FFXIVClientStructs") \
        .write(commit)

    Source(commit, A + "State.cs") \
        .replace("    public Lumina.Excel.Sheets.Recipe Recipe;\n    public Lumina.Excel.Sheets.RecipeLevelTable LevelTable;\n", "",
                 "removed the two Lumina sheet-row fields (Recipe, LevelTable); no solver reads them") \
        .write(commit)

    Source(commit, "Artisan/RawInformation/Character/Skills.cs") \
        .drop_usings("ECommons.ExcelServices") \
        .cut("    public static class SkillActionMap", "\n}\n",
             "removed SkillActionMap (action ids and levels read from the game's sheets); Level() is in ArtisanShim.cs", keep_end=True) \
        .write(commit)

    # ---- the simulator the solvers predict with ---------------------------------------------------
    Source(commit, A + "Simulator.cs") \
        .drop_usings("Artisan.GameInterop", "Artisan.GameInterop.CSExt", "Dalamud.Interface.Colors",
                     "ECommons.DalamudServices", "Lumina.Excel.Sheets", "System.Numerics") \
        .cut("    public static string ToOutputString(this CraftStatus status)", "    public enum ExecuteResult",
             "removed ToOutputString (ECommons attribute helper, UI text)") \
        .cut("    public unsafe static string SimulatorResult(", "    public static (ExecuteResult, StepState) Execute(",
             "removed SimulatorResult and GetStartingQuality (UI text; reads the live crafting log)") \
        .cut("    public static bool CannotUseAction(", "    public static bool SkipUpdates(",
             "removed CannotUseAction (UI text; reads the live inventory)") \
        .write(commit)

    Source(commit, A + "Calculations.cs") \
        .drop_usings("Artisan.RawInformation", "ECommons.DalamudServices", "Lumina.Excel.Sheets") \
        .cut("        public static int RecipeDifficulty(Recipe recipe) =>", "        public static bool ActionIsLengthyAnimation(",
             "removed the Recipe sheet helpers (RecipeDifficulty / RecipeMaxQuality / RecipeDurability)") \
        .cut("        public static int GetStartingQuality(Recipe recipe, int[] hqCount", "    }\n}\n",
             "removed GetStartingQuality (reads the Item sheet)") \
        .write(commit)

    # ---- solvers ------------------------------------------------------------------------------------
    Source(commit, A + "ISolver.cs").write(commit)

    Source(commit, A + "Solvers/StandardSolver.cs") \
        .drop_usings("ECommons.DalamudServices") \
        .write(commit)

    Source(commit, A + "Solvers/ProgressOnlySolver.cs").write(commit)

    Source(commit, A + "Solvers/MacroSolverSettings.cs").write(commit)

    Source(commit, A + "Solvers/MacroSolver.cs") \
        .drop_usings("ECommons.DalamudServices", "SharpDX.DirectWrite") \
        .write(commit)

    Source(commit, A + "Solvers/ExpertSolverProfiles.cs") \
        .drop_usings("ECommons", "ECommons.DalamudServices", "TerraFX.Interop.Windows") \
        .cut("        public void SetPerRecipeSettings(RecipeConfig recipeConfig)", "        public int GetMaxSteadyUses()",
             "removed SetPerRecipeSettings (per-recipe UI config)") \
        .write(commit)

    Source(commit, A + "Solvers/ExpertSolverSettings.cs") \
        .drop_usings("Artisan.RawInformation", "Dalamud.Bindings.ImGui", "Dalamud.Interface.Colors",
                     "Dalamud.Interface.Components", "Dalamud.Interface.Textures.TextureWraps",
                     "ECommons.DalamudServices", "ECommons.ImGuiMethods", "System.Numerics",
                     "static Artisan.RawInformation.AddonExtensions") \
        .cut_regex(r"^    public string Get\w+\(\w+ value\)\n        => value switch\n        \{.*?\n        \};\n",
                   "removed the Get...Name display-text helpers (localised action and buff names)", 10) \
        .write(commit)

    Source(commit, A + "Solvers/ExpertSolver.cs") \
        .drop_usings("Artisan.RawInformation", "ECommons.DalamudServices", "TerraFX.Interop.Windows") \
        .write(commit)

    print("Done. ArtisanShim.cs and NOTICE.md are hand-written and are not touched by this script.")


if __name__ == "__main__":
    main()
